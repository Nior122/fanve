interface MockDataContextType {
  profiles: Profile[];
  user: User | null;
  login: (email: string, role: UserRole) => void;
  logout: () => void;
  addProfile: (profile: Profile) => void;
  updateProfile: (profile: Profile) => void;
  deleteProfile: (id: string) => void;
  toggleFavorite: (profileId: string) => void;
  isFavorite: (profileId: string) => boolean;
}

const MockDataContext = createContext<MockDataContextType | undefined>(undefined);

export const MockDataProvider = ({ children }: { children: ReactNode }) => {
  const [user, setUser] = useState<User | null>(null);
  const [profiles, setProfiles] = useState<Profile[]>(PROFILES);

  const login = (email: string, role: UserRole) => {
    setUser({
      id: 'user-' + Date.now(),
      email,
      role,
      name: email.split('@')[0],
      avatarUrl: 'https://images.unsplash.com/photo-1535713875002-d1d0cf377fde?w=200&q=80',
    });
  };

  const logout = () => {
    setUser(null);
  };

  const addProfile = (profile: Profile) => {
    setProfiles(prev => [...prev, profile]);
  };

  const updateProfile = (updatedProfile: Profile) => {
    setProfiles(prev => prev.map(p => p.id === updatedProfile.id ? updatedProfile : p));
  };

  const deleteProfile = (id: string) => {
    setProfiles(prev => prev.filter(p => p.id !== id));
  };

  // Mock favorites functionality
  const [favorites, setFavorites] = useState<string[]>([]);

  const toggleFavorite = (profileId: string) => {
    setFavorites(prev =>
      prev.includes(profileId)
        ? prev.filter(id => id !== profileId)
        : [...prev, profileId]
    );
  };

  const isFavorite = (profileId: string) => favorites.includes(profileId);

  return (
    <MockDataContext.Provider value={{
      profiles,
      user,
      login,
      logout,
      addProfile,
      updateProfile,
      deleteProfile,
      toggleFavorite,
      isFavorite
    }}>
      {children}
    </MockDataContext.Provider>
  );
};

export const useMockData = () => {
  const context = useContext(MockDataContext);
  if (context === undefined) {
    throw new Error('useMockData must be used within a MockDataProvider');
  }
  return context;
};